import type { SVGProps } from "react";

/*
 * Typed, minified inline SVG icon set (Feather-style, 24x24, 2px stroke).
 * Icons were previously hand-inlined ad hoc across components; this is the
 * shared, accessible, typed set the primitives and refactored surfaces draw
 * from. No icon-font / SVG-sprite dependency — each icon is a tiny component.
 *
 * Accessibility: an icon is decorative by default (`aria-hidden`, skipped by
 * screen readers) because it almost always sits next to a text label. Pass a
 * `label` to make it a standalone image with an accessible name (e.g. an
 * icon-only control that has no adjacent text — though prefer IconButton, which
 * labels the button itself).
 */
export type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  /** Pixel size for width & height (default 20). */
  size?: number;
  /** Accessible name. Omit for decorative icons (default: aria-hidden). */
  label?: string;
};

function Icon({ size = 20, label, ...props }: IconProps & { children: React.ReactNode }) {
  const { children, ...rest } = props as IconProps & { children: React.ReactNode };
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      {...rest}
    >
      {children}
    </svg>
  );
}

